// Compares the legacy free-exercise-db catalog (data/legacy-exercises.json)
// against the new RepDB catalog (data/exercises.json) and produces a mapping
// report. Old ids are never deleted from the running app — see
// lib/exercise-service.ts's legacy fallback — this script exists to (a) give
// a human-readable audit of what mapped to what and (b) produce SQL rows for
// an optional `exercise_migration_map` table (see db/migrations), which the
// backend has no automated way to apply (no Supabase CLI in this repo) —
// applying it is a manual step for whoever owns the Supabase project.
//
// Usage: node scripts/build-exercise-migration-map.mjs

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

const fold = (value) => String(value || "")
  .toLowerCase()
  .replace(/[_-]/g, " ")
  .normalize("NFD").replace(/[̀-ͯ]/g, "")
  .replace(/[^a-z0-9 ]/g, "")
  .replace(/\s+/g, " ")
  .trim();

// A small number of legacy exercises use naming conventions different enough
// from RepDB's that normalized-name matching misses them, but they are
// unambiguously the same movement. Curated by hand, kept intentionally short.
const MANUAL_MAP = {
  Barbell_Full_Squat: "barbell-back-squat",
  Pullups: "pull-up",
  "Chin-Up": "chin-up",
  "Bent_Over_Barbell_Row": "barbell-bent-over-row",
  "Close-Grip_Front_Lat_Pulldown": "close-grip-lat-pulldown",
  "Wide-Grip_Lat_Pulldown": "wide-grip-lat-pulldown",
  "Dumbbell_Shoulder_Press": "dumbbell-shoulder-press",
  "Barbell_Shoulder_Press": "barbell-overhead-press",
  "Romanian_Deadlift": "romanian-deadlift",
  "Clean_Deadlift": "deadlift",
};

function levenshtein(a, b) {
  const dp = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 0; j <= b.length; j += 1) dp[0][j] = j;
  for (let i = 1; i <= a.length; i += 1) {
    for (let j = 1; j <= b.length; j += 1) {
      dp[i][j] = a[i - 1] === b[j - 1]
        ? dp[i - 1][j - 1]
        : 1 + Math.min(dp[i - 1][j], dp[i][j - 1], dp[i - 1][j - 1]);
    }
  }
  return dp[a.length][b.length];
}

const legacy = JSON.parse(await readFile(join(root, "data", "legacy-exercises.json"), "utf8"));
const current = JSON.parse(await readFile(join(root, "data", "exercises.json"), "utf8"));

const currentByNormalizedName = new Map(current.map((exercise) => [fold(exercise.name), exercise]));
const currentIds = new Set(current.map((exercise) => exercise.id));

const rows = legacy.map((oldExercise) => {
  const normalizedOld = fold(oldExercise.name);

  if (MANUAL_MAP[oldExercise.id] && currentIds.has(MANUAL_MAP[oldExercise.id])) {
    return { old_exercise_id: oldExercise.id, new_exercise_id: MANUAL_MAP[oldExercise.id], match_type: "manual", confidence: 0.95 };
  }

  const exact = currentByNormalizedName.get(normalizedOld);
  if (exact) {
    return { old_exercise_id: oldExercise.id, new_exercise_id: exact.id, match_type: "exact", confidence: 1 };
  }

  // Fuzzy: smallest edit distance among current catalog names, only accepted
  // when it's close relative to name length (avoids false positives on short
  // names like "Dip" matching everything).
  let best = null;
  let bestDistance = Infinity;
  for (const candidate of current) {
    const normalizedNew = fold(candidate.name);
    const distance = levenshtein(normalizedOld, normalizedNew);
    if (distance < bestDistance) {
      bestDistance = distance;
      best = candidate;
    }
  }
  const threshold = Math.max(2, Math.round(normalizedOld.length * 0.2));
  if (best && bestDistance <= threshold) {
    const confidence = Math.max(0.5, 1 - bestDistance / Math.max(normalizedOld.length, 1));
    return { old_exercise_id: oldExercise.id, new_exercise_id: best.id, match_type: "normalized_name", confidence: Math.round(confidence * 100) / 100 };
  }

  return { old_exercise_id: oldExercise.id, new_exercise_id: null, match_type: "no_match", confidence: 0 };
});

const summary = rows.reduce((acc, row) => {
  acc[row.match_type] = (acc[row.match_type] || 0) + 1;
  return acc;
}, {});

await writeFile(join(root, "data", "exercise_migration_map.json"), `${JSON.stringify(rows, null, 2)}\n`);

const sqlValues = rows
  .map((row) => `('${row.old_exercise_id.replace(/'/g, "''")}', ${row.new_exercise_id ? `'${row.new_exercise_id}'` : "NULL"}, '${row.match_type}', ${row.confidence}, ${row.new_exercise_id ? "'mapped'" : "'unmapped'"})`)
  .join(",\n  ");

const sql = `-- Exercise migration map: legacy free-exercise-db id -> RepDB id.
-- Generated by scripts/build-exercise-migration-map.mjs — apply manually via
-- the Supabase SQL editor (this repo has no automated migration runner; see
-- db/migrations/README or the other files in this directory for the same
-- pattern). Re-running the generator + this file is idempotent (ON CONFLICT).

create table if not exists exercise_migration_map (
  old_exercise_id text primary key,
  new_exercise_id text,
  match_type text not null check (match_type in ('exact', 'normalized_name', 'manual', 'no_match')),
  confidence numeric not null default 0,
  migration_status text not null default 'unmapped' check (migration_status in ('mapped', 'unmapped')),
  created_at timestamptz not null default now()
);

insert into exercise_migration_map (old_exercise_id, new_exercise_id, match_type, confidence, migration_status)
values
  ${sqlValues}
on conflict (old_exercise_id) do update set
  new_exercise_id = excluded.new_exercise_id,
  match_type = excluded.match_type,
  confidence = excluded.confidence,
  migration_status = excluded.migration_status;
`;

const timestamp = new Date().toISOString().replace(/[-:]/g, "").replace(/\..+/, "").replace("T", "");
await writeFile(join(root, "db", "migrations", `${timestamp}_exercise_migration_map.sql`), sql);

console.log(`Legacy exercises: ${legacy.length}`);
console.log(`Match summary: ${JSON.stringify(summary)}`);
console.log("Wrote data/exercise_migration_map.json and db/migrations/*_exercise_migration_map.sql (not applied — see file header).");
